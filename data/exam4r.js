function moon(cx, cy, r, ph, sw = 2.5) {
  const base = `<circle cx="${cx}" cy="${cy}" r="${r}" fill="${DARKM}" stroke="${INK}" stroke-width="${sw}"/>`;
  if (ph <= 0.001 || ph >= 0.999) return base;
  if (Math.abs(ph - 0.5) < 0.001) return `<circle cx="${cx}" cy="${cy}" r="${r}" fill="${YEL}" stroke="${INK}" stroke-width="${sw}"/>`;
  const rx = +(r * Math.abs(Math.cos(2 * Math.PI * ph))).toFixed(1), top = `${cx},${cy - r}`, bot = `${cx},${cy + r}`;
  const d = ph < 0.5 ? `M${top} A${r},${r} 0 0 1 ${bot} A${rx},${r} 0 0 ${ph < 0.25 ? 0 : 1} ${top} Z` : `M${top} A${r},${r} 0 0 0 ${bot} A${rx},${r} 0 0 ${ph < 0.75 ? 0 : 1} ${top} Z`;
  return base + `<path d="${d}" fill="${YEL}" stroke="${INK}" stroke-width="${sw * 0.6}"/>`;
}
