const moon = (cx, cy, r, p) => {
  let s = `<circle cx="${cx}" cy="${cy}" r="${r}" fill="${DARK}" stroke="${INK}" stroke-width="2"/>`;
  if (p <= 0.001 || p >= 0.999) return s;
  if (Math.abs(p - 0.5) < 0.001) return `<circle cx="${cx}" cy="${cy}" r="${r}" fill="${YEL}" stroke="${INK}" stroke-width="2"/>`;
  const rx = (r * Math.abs(Math.cos(2 * Math.PI * p))).toFixed(1);
  const top = `${cx},${cy - r}`, bot = `${cx},${cy + r}`;
  const d = p < 0.5
    ? `M${top} A${r},${r} 0 0 1 ${bot} A${rx},${r} 0 0 ${p < 0.25 ? 0 : 1} ${top} Z`
    : `M${top} A${r},${r} 0 0 0 ${bot} A${rx},${r} 0 0 ${p < 0.75 ? 0 : 1} ${top} Z`;
  return s + `<path d="${d}" fill="${YEL}" stroke="${INK}" stroke-width="1.5"/>`;
};

