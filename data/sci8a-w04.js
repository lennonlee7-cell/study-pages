// 6. 波形：振幅看響度、疏密看音調、形狀看音色
const wave = (x0, y0, w, amp, cycles, shape) => {
  const pts = [];
  for (let i = 0; i <= 120; i++) {
    const p = (i / 120) * cycles * 2 * Math.PI;
    const v = shape ? (Math.sin(p) + 0.55 * Math.sin(2 * p + 0.6) + 0.3 * Math.sin(3 * p)) / 1.45 : Math.sin(p);
    pts.push(`${(x0 + (i / 120) * w).toFixed(1)},${(y0 - amp * v).toFixed(1)}`);
  }
  return `<line x1="${x0}" y1="${y0}" x2="${x0 + w}" y2="${y0}" stroke="${GREY}" stroke-width="2"/><polyline points="${pts.join(" ")}" fill="none" stroke="${INK}" stroke-width="3" stroke-linejoin="round"/>`;
};
