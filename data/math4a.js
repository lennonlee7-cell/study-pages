// 直式乘法：數字由程式算
function longMul(a, b) {
  const CW = 24, RH = 32, X = 190, bd = String(b).split("").reverse().map(Number);
  const num = (s, y, shift = 0, c = INK) => s.split("").reverse().map((ch, i) => T(X - (i + shift) * CW, y, ch, { fs: 22, c, b: 1 })).join("");
  const total = a * b, wid = String(total).length;
  const lineX = X - (wid + 1) * CW + 10;
  let y = 34, s = num(String(a), y); y += RH;
  s += num(String(b), y) + T(X - (Math.max(String(b).length, String(a).length)) * CW, y, "×", { fs: 22, b: 1 });
  y += 10; s += L(lineX, y, X + 14, y); y += 26;
  bd.forEach((d, i) => {
    if (i) s += T(X, y, "0", { fs: 22, c: GRAY });
    s += num(String(a * d), y, i, i ? BLUE : RED);
    s += T(X + 30, y - 2, `← ${a} × ${d * 10 ** i}`, { fs: 15, a: "start", c: i ? BLUE : RED });
    y += RH;
  });
  if (bd.length > 1) {
    y += -RH + 10; s += L(lineX, y, X + 14, y); y += 26;
    s += num(String(total), y) + T(X + 30, y - 2, "← 上下相加", { fs: 15, a: "start", b: 1 });
    y += RH;
  }
  return frame(470, y - 8, s, `${a} 乘以 ${b} 的直式`);
}

// 直式除法：數字由程式算
function longDiv(n, dv) {
  const CW = 24, RH = 32, X0 = 120, ds = String(n).split("").map(Number), N = ds.length;
  const R = (v, y, col, c = INK) => String(v).split("").reverse().map((ch, i) => T(X0 + (col - i) * CW, y, ch, { fs: 22, c, b: 1 })).join("");
  const top = 34, right = X0 + (N - 1) * CW;
  let y = top + RH, cur = 0, started = false;
  let s = `<path d="M${X0 - 18},${y + 8} Q${X0 - 8},${y - 8} ${X0 - 16},${top + 8} L${right + 16},${top + 8}" fill="none" stroke="${INK}" stroke-width="2.5"/>` +
    T(X0 - 26, y, dv, { fs: 22, b: 1, a: "end" }) + ds.map((d, i) => T(X0 + i * CW, y, d, { fs: 22, b: 1 })).join("");
  ds.forEach((d, i) => {
    cur = cur * 10 + d;
    const k = Math.floor(cur / dv);
    if (!started && k === 0) return;
    started = true;
    s += T(X0 + i * CW, top, k, { fs: 22, c: RED, b: 1 });
    if (k === 0) return; // 不夠除：商寫 0，繼續放下一位
    const p = k * dv, w = String(cur).length;
    y += RH;
    s += R(p, y, i, BLUE) + T(right + 34, y - 2, `← ${dv} × ${k}`, { fs: 15, a: "start", c: BLUE });
    y += 10; s += L(X0 + (i - w + 1) * CW - 12, y, X0 + i * CW + 12, y);
    y += RH - 10;
    cur -= p;
    // 餘數加上放下來的數字，寫到下一個夠除的位數；都不夠除就是最後的餘數
    let j = i + 1, show = cur;
    while (j < N) { show = show * 10 + ds[j]; if (Math.floor(show / dv) > 0) break; j++; }
    s += R(show, y, Math.min(j, N - 1));
  });
  if (cur) s += T(right + 34, y - 2, `← 餘 ${cur}（比 ${dv} 小）`, { fs: 15, a: "start", b: 1, c: RED });
  return frame(470, y + 16, s, `${n} 除以 ${dv} 的直式`);
}

// 量角器：外圈從左邊 0 開始、內圈從右邊 0 開始
function proto(deg, side = "right", id = "p") {
  const cx = 235, cy = 205, R = 165, phi = side === "right" ? deg : 180 - deg;
  let s = `<path d="M${cx - R},${cy} A${R},${R} 0 0 1 ${cx + R},${cy} Z" fill="${SOFT}" stroke="${INK}" stroke-width="2.5"/>`;
  for (let d = 0; d <= 180; d += 10) { const [a, b] = pol(cx, cy, R, d), [c, e] = pol(cx, cy, R - (d % 30 ? 8 : 14), d); s += L(a, b, c, e, { w: d % 30 ? 1.2 : 2 }); }
  const [rx, ry] = pol(cx, cy, R - 4, phi);
  s += L(cx - R, cy, cx + R, cy, { w: 2 });
  s += L(cx, cy, side === "right" ? cx + R : cx - R, cy, { c: RED, w: 5 }) + L(cx, cy, rx, ry, { c: RED, w: 5 });
  s += side === "right" ? arc(cx, cy, 34, 0, phi) : arc(cx, cy, 34, phi, 180);
  // 數字畫在紅線上面、加底色，邊經過的那個數字才讀得到
  for (let d = 0; d <= 180; d += 30) {
    const [ox, oy] = pol(cx, cy, R + 14, d), [ix, iy] = pol(cx, cy, R - 30, d), lift = d === 0 || d === 180 ? -6 : 5;
    s += T(ox, oy + lift, 180 - d, { fs: 15, b: 1 }) +
      T(ix, iy + lift, d, { fs: 15, c: BLUE, b: 1 }).replace("<text ", `<text stroke="${SOFT}" stroke-width="5" paint-order="stroke" `);
  }
  s += `<circle cx="${cx}" cy="${cy}" r="5" fill="${RED}"/>` + T(cx, cy + 22, "中心點對準頂點", { fs: 15 });
  return frame(470, 236, s, "量角器量角");
}

