// 三角形小工具
const P = (pts, fill = SOFT) => `<polygon points="${pts.map((p) => p.join(",")).join(" ")}" fill="${fill}" stroke="${INK}" stroke-width="2.5" stroke-linejoin="round"/>`;
const tick = (p, q, n = 1) => {
  const mx = (p[0] + q[0]) / 2, my = (p[1] + q[1]) / 2, dx = q[0] - p[0], dy = q[1] - p[1], len = Math.hypot(dx, dy), ux = dx / len, uy = dy / len;
  let s = "";
  for (let i = 0; i < n; i++) { const o = (i - (n - 1) / 2) * 6; s += L(fx(mx + ux * o - uy * 6), fx(my + uy * o + ux * 6), fx(mx + ux * o + uy * 6), fx(my + uy * o - ux * 6), { c: RED, w: 2.5 }); }
  return s;
};
// 在 v 點、朝 a、b 兩邊畫直角記號
const rightMark = (v, a, b, r = 11) => {
  const un = (p) => { const dx = p[0] - v[0], dy = p[1] - v[1], l = Math.hypot(dx, dy); return [dx / l * r, dy / l * r]; };
  const [ax, ay] = un(a), [bx, by] = un(b);
  return `<path d="M${fx(v[0] + ax)},${fx(v[1] + ay)} L${fx(v[0] + ax + bx)},${fx(v[1] + ay + by)} L${fx(v[0] + bx)},${fx(v[1] + by)}" fill="none" stroke="${RED}" stroke-width="2.5"/>`;
};
const move = (pts, x, y, k = 1) => pts.map(([a, b]) => [fx(x + a * k), fx(y + b * k)]);

